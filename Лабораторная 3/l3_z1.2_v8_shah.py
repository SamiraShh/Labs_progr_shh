# Ввод целого числа N > 0
ok_n = False
n = 0
while not ok_n:
    try:
        n = int(input("Введите целое число N > 0: "))
        if n > 0:
            ok_n = True
        else:
            print("Ошибка: число N должно быть больше 0. Повторите ввод")
    except ValueError:
        print("Ошибка: введите целое число, а не текст. Повторите ввод")

# Сохраняем исходное значение N для вывода в конце(т.к. переменная n будет уменьшаться)
orig_n = n

# Находим количество и сумму цифр числа
count_digits = 0
sum_digits = 0

while n > 0:
    digit = n % 10          # получаем последнюю цифру числа
    sum_digits += digit     # добавляем цифру к сумме
    count_digits += 1       # увеличиваем счетчик количества цифр
    n = n // 10             # отбрасываем последнюю цифру

print("\nРезультаты расчета:")
print(f"Исходное число N: {orig_n}")
print(f"Количество цифр: {count_digits}")
print(f"Сумма цифр: {sum_digits}")